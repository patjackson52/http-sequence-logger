import { readFileSync, writeFileSync } from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

// Compile in Node, never with new Function in the browser. The generated ESM
// validator preserves the exact same AJV formats/checks as the reference CLI.
const schema = JSON.parse(readFileSync(new URL('../schema/event.schema.json', import.meta.url), 'utf8'));
const ajv = new Ajv2020({ allErrors: true, strict: true, strictTypes: false, strictRequired: false, code: { source: true, esm: true } });
addFormats(ajv);
let code = standaloneCode(ajv, ajv.compile(schema));
const imports = new Map();
code = code.replace(/require\("([^"]+)"\)/g, (_match, specifier) => {
  if (!imports.has(specifier)) imports.set(specifier, `runtime${imports.size}`);
  return imports.get(specifier);
});
const header = [...imports].map(([specifier, name]) => `import ${name} from ${JSON.stringify(`${specifier}.js`)};`).join('\n');
writeFileSync(new URL('../shared/event-validator.mjs', import.meta.url), `// Generated by scripts/build-validator.mjs. Do not edit.\n${header}\n${code}\n`);
